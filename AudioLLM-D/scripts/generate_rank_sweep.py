#!/usr/bin/env python
"""Generate the scoped LoRA/DoRA rank sweep configs (ticket 1.5).

Sweep = LM rank in {8, 16, 32, 64} x {LoRA, DoRA} = 8 runs. Held constant:
  * encoder rank = LM rank / 2
  * alpha / r = 2  (so alpha = 2*r for both LM and encoder)
  * everything else (tiered focal loss, per-component LRs, epochs, seed) from
    the base config.

Each generated config is the base config with only lora.r, lora.alpha,
lora.use_dora, lora.audio_encoder_rank, lora.audio_encoder_alpha, output_dir and
the wandb name/tags changed.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

LM_RANKS = [8, 16, 32, 64]
VARIANTS = [("lora", False), ("dora", True)]
ALPHA_OVER_R = 2


def make_config(base: dict, *, rank: int, variant: str, use_dora: bool, output_root: str) -> dict:
    cfg = dict(base)
    lora = dict(base["lora"])
    enc_rank = rank // 2
    lora["r"] = rank
    lora["alpha"] = ALPHA_OVER_R * rank
    lora["use_dora"] = use_dora
    lora["audio_encoder_rank"] = enc_rank
    lora["audio_encoder_alpha"] = ALPHA_OVER_R * enc_rank
    cfg["lora"] = lora

    run_name = f"qwen2-audio-dementia-v3-{variant}-r{rank}"
    cfg["output_dir"] = str(Path(output_root) / run_name)

    wandb_cfg = dict(base.get("wandb") or {})
    wandb_cfg["name"] = run_name
    tags = [t for t in wandb_cfg.get("tags", []) if t not in {"lora", "dora", "tiered-focal"}]
    wandb_cfg["tags"] = [*tags, variant, "rank-sweep", f"r{rank}"]
    cfg["wandb"] = wandb_cfg
    return cfg


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--base-config",
        default="configs/qwen2_audio_lora_v3.yaml",
        help="Base v3 tiered-focal config to vary rank/DoRA over.",
    )
    parser.add_argument("--out-dir", default="configs/sweep", help="Where to write the 8 configs.")
    parser.add_argument(
        "--output-root",
        default="/scratch/nathan/lora_run/outputs/rank_sweep",
        help="Root output_dir for the runs (each run gets a subdir).",
    )
    args = parser.parse_args()

    base = yaml.safe_load(Path(args.base_config).read_text(encoding="utf-8"))
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    written: list[Path] = []
    for rank in LM_RANKS:
        for variant, use_dora in VARIANTS:
            cfg = make_config(
                base, rank=rank, variant=variant, use_dora=use_dora, output_root=args.output_root
            )
            path = out_dir / f"{variant}_r{rank}.yaml"
            header = (
                f"# AUTO-GENERATED by scripts/generate_rank_sweep.py from {args.base_config}.\n"
                f"# Sweep cell: {variant.upper()}, LM rank={rank}, encoder rank={rank // 2}, "
                f"alpha/r={ALPHA_OVER_R}. Do not hand-edit; regenerate instead.\n"
            )
            path.write_text(header + yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
            written.append(path)

    print(f"Wrote {len(written)} sweep configs to {out_dir}/:")
    for path in written:
        print(f"  {path}")
    print("\nRun each with, e.g.:")
    print("  for c in %s/*.yaml; do \\" % out_dir)
    print('    PYTHONPATH=src python scripts/train_lora.py --config "$c"; \\')
    print("  done")
    print("\nThen build the results table:")
    print(
        "  PYTHONPATH=src python scripts/build_sweep_table.py "
        f"--runs-root {args.output_root} "
        "--reference-dir /scratch/nathan/lora_run/outputs/qwen2-audio-dementia-lora-v2"
    )


if __name__ == "__main__":
    main()
